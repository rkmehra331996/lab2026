export const isCategoryMatch = (testCat: string, targetCat: string): boolean => {
  if (!testCat || !targetCat) return false;
  if (targetCat === 'All') return true;
  const a = testCat.toLowerCase().trim();
  const b = targetCat.toLowerCase().trim();
  if (a === b) return true;

  if ((a.includes('hematology') || a.includes('blood test')) && (b.includes('hematology') || b.includes('blood test'))) return true;
  if ((a.includes('biochem') || a.includes('clinical biochem')) && (b.includes('biochem') || b.includes('clinical biochem'))) return true;
  if (a.includes('clinical path') && b.includes('clinical path')) return true;
  if ((a.includes('serology') || a.includes('immunol')) && (b.includes('serology') || b.includes('immunol'))) return true;
  if ((a.includes('microbiol') || a.includes('culture')) && (b.includes('microbiol') || b.includes('culture'))) return true;
  if ((a.includes('hormone') || a.includes('endocrin')) && (b.includes('hormone') || b.includes('endocrin'))) return true;
  if ((a.includes('coagulation') || a.includes('clotting')) && (b.includes('coagulation') || b.includes('clotting'))) return true;
  if ((a.includes('histopath') || a.includes('cytology') || a.includes('biopsy') || a.includes('fnac')) && (b.includes('histopath') || b.includes('cytology') || b.includes('biopsy') || b.includes('fnac'))) return true;
  if ((a.includes('pcr') || a.includes('molecular')) && (b.includes('pcr') || b.includes('molecular'))) return true;
  if (a.includes('blood bank') && b.includes('blood bank')) return true;
  if (a.includes('tumor') && b.includes('tumor')) return true;
  if (a.includes('special') && b.includes('special')) return true;

  return false;
};

